//! Optional boundary-to-heightfield traversal links.
use super::BakeConfig;
use crate::common::{ceilf, floorf, sqrtf};
use crate::recast::{CompactHeightfield, Heightfield, MESH_NULL_IDX, NULL_AREA, PolyMesh};
use crate::{Error, Workspace};
use alloc::vec::Vec;

/// Parameters for one traversal kind, in world units.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct LinkLimits {
    /// Maximum horizontal reach.
    pub distance: f32,
    /// Maximum rise above the departure.
    pub up: f32,
    /// Maximum fall below the departure.
    pub down: f32,
    /// Height added to the straight clearance segment.
    pub clearance: f32,
}

/// Opt-in extraction settings. Indices in `area_ids` and `flags` are drop, jump, climb.
/// Every kind requires an absolute height change greater than `walkable_climb`;
/// in particular, equal-height gap jumps are excluded by this minimum-height rule.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct LinkExtraction {
    /// Downward links.
    pub drop: Option<LinkLimits>,
    /// Links across gaps.
    pub jump: Option<LinkLimits>,
    /// Upward ledge links.
    pub climb: Option<LinkLimits>,
    /// Sample spacing along each boundary, in cells; must be positive.
    pub spacing_cells: u16,
    /// Caller-selected area per kind.
    pub area_ids: [u8; 3],
    /// Caller-selected flags per kind.
    pub flags: [u16; 3],
}
impl LinkExtraction {
    pub(super) fn validate(&self) -> Result<(), Error> {
        if self.spacing_cells == 0 || self.area_ids.iter().any(|&a| a > 63) {
            return Err(Error::InvalidParameter("link extraction settings"));
        }
        for l in [self.drop, self.jump, self.climb].into_iter().flatten() {
            if [l.distance, l.up, l.down, l.clearance]
                .iter()
                .any(|v| !v.is_finite() || *v < 0.0)
            {
                return Err(Error::InvalidParameter("link extraction limits"));
            }
        }
        Ok(())
    }
    pub(super) fn reach_cells(&self, cs: f32) -> Result<i32, Error> {
        let reach = [self.drop, self.jump, self.climb]
            .into_iter()
            .flatten()
            .map(|l| l.distance)
            .fold(0.0f32, f32::max);
        let cells = ceilf(reach / cs);
        if !cells.is_finite() || cells >= (i32::MAX / 4) as f32 {
            return Err(Error::SizeOverflow);
        }
        Ok(cells as i32)
    }
}

/// Traversal generated by boundary sampling.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LinkKind {
    /// Downward traversal.
    Drop,
    /// Gap traversal.
    Jump,
    /// Upward traversal.
    Climb,
}
/// One generated, one-directional connection, also installed in the tile bytes.
#[derive(Clone, Debug)]
pub struct ExtractedLink {
    /// Departure on the boundary polygon.
    pub start: [f32; 3],
    /// Landing on a walkable heightfield span.
    pub end: [f32; 3],
    /// Endpoint attachment radius.
    pub radius: f32,
    /// Traversal kind.
    pub kind: LinkKind,
    /// Caller-selected area.
    pub area: u8,
    /// Caller-selected flags.
    pub flags: u16,
}

// Inspection records use bit equality so serialized/default-output comparisons
// can distinguish signed zero and remain reflexive for caller-written values.
impl PartialEq for ExtractedLink {
    fn eq(&self, other: &Self) -> bool {
        self.start.map(f32::to_bits) == other.start.map(f32::to_bits)
            && self.end.map(f32::to_bits) == other.end.map(f32::to_bits)
            && self.radius.to_bits() == other.radius.to_bits()
            && self.kind == other.kind
            && self.area == other.area
            && self.flags == other.flags
    }
}
impl Eq for ExtractedLink {}

pub(super) fn halo(c: &BakeConfig) -> Result<i32, Error> {
    let base = c
        .recast
        .walkable_radius
        .checked_add(3)
        .ok_or(Error::SizeOverflow)?;
    match c.links {
        None => Ok(base),
        Some(l) => base
            .checked_add(l.reach_cells(c.recast.cs)?)
            .ok_or(Error::SizeOverflow),
    }
}

fn column(h: &CompactHeightfield, p: [f32; 3]) -> Option<usize> {
    let x = floorf((p[0] - h.bmin[0]) / h.cs) as i32;
    let z = floorf((p[2] - h.bmin[2]) / h.cs) as i32;
    if x < 0 || z < 0 || x >= h.width || z >= h.height {
        None
    } else {
        Some(x as usize + z as usize * h.width as usize)
    }
}

fn clear(
    ws: &mut Workspace,
    solid: &Heightfield,
    a: [f32; 3],
    b: [f32; 3],
    lift: f32,
    height: f32,
) -> Result<bool, Error> {
    let dx = b[0] - a[0];
    let dz = b[2] - a[2];
    let horizontal = dx.abs().max(dz.abs()) / solid.cs;
    let vertical = (b[1] - a[1]).abs() / solid.ch;
    let steps = ceilf(horizontal.max(vertical) * 2.0).max(1.0);
    if !steps.is_finite() || steps > i32::MAX as f32 {
        return Err(Error::SizeOverflow);
    }
    let n = steps as usize;
    // The departure and landing are included. Each half-cell step checks the full
    // swept body's vertical extent; solid spans remain available after erosion.
    for i in 0..=n {
        ws.work(1)?;
        let t = i as f32 / n as f32;
        let x = floorf((a[0] + dx * t - solid.bmin[0]) / solid.cs) as i32;
        let z = floorf((a[2] + dz * t - solid.bmin[2]) / solid.cs) as i32;
        if x < 0 || z < 0 || x >= solid.width || z >= solid.height {
            return Ok(false);
        }
        let y = a[1] + (b[1] - a[1]) * t + lift;
        for span in solid.column((x + z * solid.width) as usize) {
            ws.work(1)?;
            let lo = solid.bmin[1] + span.smin as f32 * solid.ch;
            let hi = solid.bmin[1] + span.smax as f32 * solid.ch;
            if hi > y && lo < y + height {
                return Ok(false);
            }
        }
    }
    Ok(true)
}

// Resolve interior landings to the actual polygon, not merely a connected
// region. Halo landings have no local polygon and get a unique span key, so
// samples cannot accidentally merge different polygons in another tile.
fn landing_key(
    ws: &mut Workspace,
    mesh: &PolyMesh,
    end: [f32; 3],
    span: usize,
) -> Result<usize, Error> {
    let nvp = mesh.nvp as usize;
    for p in 0..mesh.npolys as usize {
        let poly = &mesh.polys[p * nvp * 2..p * nvp * 2 + nvp];
        let count = poly.iter().take_while(|&&v| v != MESH_NULL_IDX).count();
        let mut inside = true;
        let mut ymin = f32::INFINITY;
        let mut ymax = f32::NEG_INFINITY;
        for i in 0..count {
            ws.work(1)?;
            let a = poly[i] as usize * 3;
            let b = poly[(i + 1) % count] as usize * 3;
            let ax = mesh.bmin[0] + mesh.verts[a] as f32 * mesh.cs;
            let az = mesh.bmin[2] + mesh.verts[a + 2] as f32 * mesh.cs;
            let bx = mesh.bmin[0] + mesh.verts[b] as f32 * mesh.cs;
            let bz = mesh.bmin[2] + mesh.verts[b + 2] as f32 * mesh.cs;
            let y = mesh.bmin[1] + mesh.verts[a + 1] as f32 * mesh.ch;
            ymin = ymin.min(y);
            ymax = ymax.max(y);
            if (bx - ax) * (end[2] - az) - (bz - az) * (end[0] - ax) > 0.0 {
                inside = false;
            }
        }
        if inside && end[1] >= ymin - mesh.ch * 2.0 && end[1] <= ymax + mesh.ch * 2.0 {
            return Ok(p);
        }
    }
    (mesh.npolys as usize)
        .checked_add(span)
        .ok_or(Error::SizeOverflow)
}

/// Internal fields are produced by the checked bake pipeline.
pub(super) fn extract(
    ws: &mut Workspace,
    c: &BakeConfig,
    mesh: &PolyMesh,
    h: &CompactHeightfield,
    solid: &Heightfield,
) -> Result<Vec<ExtractedLink>, Error> {
    let Some(opts) = c.links else {
        return Ok(Vec::new());
    };
    let mut out = Vec::new();
    let nvp = mesh.nvp as usize;
    for p in 0..mesh.npolys as usize {
        let poly = &mesh.polys[p * nvp * 2..(p + 1) * nvp * 2];
        let count = poly[..nvp]
            .iter()
            .take_while(|&&v| v != MESH_NULL_IDX)
            .count();
        for e in 0..count {
            ws.work(1)?;
            if poly[nvp + e] != MESH_NULL_IDX {
                continue;
            }
            let vertex = |j: usize| {
                let v = poly[j] as usize * 3;
                [
                    mesh.bmin[0] + mesh.verts[v] as f32 * mesh.cs,
                    mesh.bmin[1] + mesh.verts[v + 1] as f32 * mesh.ch,
                    mesh.bmin[2] + mesh.verts[v + 2] as f32 * mesh.cs,
                ]
            };
            let a = vertex(e);
            let b = vertex((e + 1) % count);
            let dx = b[0] - a[0];
            let dz = b[2] - a[2];
            let scale = dx.abs().max(dz.abs());
            if scale == 0.0 {
                continue;
            }
            let len = scale * sqrtf((dx / scale) * (dx / scale) + (dz / scale) * (dz / scale));
            if !len.is_finite() {
                return Err(Error::InvalidParameter("link coordinate range"));
            }
            // Recast polygons are clockwise in xz; the left normal points out.
            let normal = [-dz / len, dx / len];
            let samples = ceilf(len / h.cs / opts.spacing_cells as f32).max(1.0) as usize;
            for (kind_index, limits) in [opts.drop, opts.jump, opts.climb].into_iter().enumerate() {
                let Some(limits) = limits else {
                    continue;
                };
                let mut run: Vec<(ExtractedLink, usize)> = Vec::new();
                for sample in 0..samples {
                    ws.work(1)?;
                    let cells =
                        sample * opts.spacing_cells as usize + opts.spacing_cells as usize / 2;
                    let t = (cells as f32 * h.cs / len).min(1.0);
                    let start = [a[0] + dx * t, a[1] + (b[1] - a[1]) * t, a[2] + dz * t];
                    let reach = limits.distance / h.cs;
                    let first = c.recast.walkable_radius.saturating_add(1).max(1);
                    let mut found = None;
                    'targets: for d in first..=floorf(reach) as i32 {
                        ws.work(1)?;
                        let target = [
                            start[0] + normal[0] * d as f32 * h.cs,
                            start[1],
                            start[2] + normal[1] * d as f32 * h.cs,
                        ];
                        let Some(col) = column(h, target) else {
                            continue;
                        };
                        let cell = &h.cells[col];
                        // Highest acceptable walkable landing in the column.
                        for si in
                            (cell.index as usize..cell.index as usize + cell.count as usize).rev()
                        {
                            ws.work(1)?;
                            let span = &h.spans[si];
                            if h.areas[si] == NULL_AREA
                                || span.reg == 0
                                || span.h as f32 * h.ch < c.walkable_height
                            {
                                continue;
                            }
                            let mut end = target;
                            end[1] = h.bmin[1] + span.y as f32 * h.ch;
                            let dy = end[1] - start[1];
                            if dy > limits.up || -dy > limits.down || dy.abs() <= c.walkable_climb {
                                continue;
                            }
                            if (kind_index == 0 && dy >= 0.0) || (kind_index == 2 && dy <= 0.0) {
                                continue;
                            }
                            let clear_path = if kind_index == 1 {
                                let raised_start =
                                    [start[0], start[1] + limits.clearance, start[2]];
                                let raised_end = [end[0], end[1] + limits.clearance, end[2]];
                                clear(ws, solid, start, raised_start, 0.0, c.walkable_height)?
                                    && clear(ws, solid, end, raised_end, 0.0, c.walkable_height)?
                                    && clear(
                                        ws,
                                        solid,
                                        start,
                                        end,
                                        limits.clearance,
                                        c.walkable_height,
                                    )?
                            } else {
                                let (upper, lower) =
                                    if dy < 0.0 { (start, end) } else { (end, start) };
                                let over = [lower[0], upper[1], lower[2]];
                                clear(ws, solid, upper, over, 0.0, c.walkable_height)?
                                    && clear(ws, solid, lower, over, 0.0, c.walkable_height)?
                            };
                            if !clear_path {
                                continue;
                            }
                            let target_key = landing_key(ws, mesh, end, si)?;
                            found = Some((
                                ExtractedLink {
                                    start,
                                    end,
                                    radius: h.cs,
                                    kind: [LinkKind::Drop, LinkKind::Jump, LinkKind::Climb]
                                        [kind_index],
                                    area: opts.area_ids[kind_index],
                                    flags: opts.flags[kind_index],
                                },
                                target_key,
                            ));
                            break 'targets;
                        }
                    }
                    // Runs merge only consecutive samples with the same landing polygon.
                    // Choose a sampled centre, preserving its clearance proof.
                    if found
                        .as_ref()
                        .zip(run.last())
                        .is_some_and(|(a, b)| a.1 != b.1)
                        || found.is_none()
                    {
                        flush(ws, &mut run, &mut out)?;
                    }
                    if let Some(link) = found {
                        ws.push(&mut run, link)?;
                    }
                }
                flush(ws, &mut run, &mut out)?;
            }
        }
    }
    Ok(out)
}
fn flush(
    ws: &mut Workspace,
    run: &mut Vec<(ExtractedLink, usize)>,
    out: &mut Vec<ExtractedLink>,
) -> Result<(), Error> {
    if !run.is_empty() {
        ws.push(out, run[run.len() / 2].0.clone())?;
        run.clear();
    }
    Ok(())
}
